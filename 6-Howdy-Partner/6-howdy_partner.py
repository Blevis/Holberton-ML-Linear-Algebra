#!/usr/bin/env python3
"""
Module to concatenate two arrays.
"""


def cat_arrays(arr1, arr2):
    """
    Concatenates two arrays into a new list.

    Args:
        arr1 (list): First list of ints/floats.
        arr2 (list): Second list of ints/floats.

    Returns:
        list: A new list containing elements from both arr1 and arr2.
    """
    return arr1 + arr2
